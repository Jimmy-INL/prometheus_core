#!/usr/bin/env bash
# Generate a merged docker-compose.agents.yml from per-agent compose files.
# Produces a single file with all agent services and paths adjusted to be
# project-root-relative, with explicit build contexts.  This avoids the
# compose 'include:' directive which podman-compose does not fully support.
set -euo pipefail

if [ $# -lt 1 ]; then
    echo "Usage: $0 <agent-compose-file> ..." >&2
    exit 1
fi

PROMETHEUS_API_BASE_IMAGE_HASH=$(awk '/PROMETHEUS_API_BASE_IMAGE_HASH:/ { print $2; exit }' docker-compose.yml)

# ── Header ──────────────────────────────────────────────────────────────────
cat <<'EOF'
# Auto-generated by 'make generate' — do not edit by hand.
# Re-run 'make generate' after checking out or removing agent submodules.

services:
EOF

# ── Services + volumes ──────────────────────────────────────────────────────
all_vol_entries=""

for f in "$@"; do
    agent_dir=$(dirname "$f")

    # Emit transformed service block:
    #   1. Strip the top-level 'services:' key (we already printed one above).
    #   2. Replace ../../ with ./ so paths are project-root-relative.
    #   3. After "    build:" insert an explicit "      context: ./<agent_dir>".
    #   4. Skip the top-level 'volumes:' section (collected separately below).
    awk -v dir="$agent_dir" -v hash="$PROMETHEUS_API_BASE_IMAGE_HASH" '
        /^services:/            { svc=1; vol=0; next }
        /^volumes:/             { svc=0; vol=1; next }
        /^[^ #]/ && svc        { svc=0 }
        /^[^ #]/ && vol        { vol=0 }
        svc {
            gsub(/\.\.\/\.\.\//, "./")
            print
            if ($0 ~ /^    build:[[:space:]]*$/) print "      context: ./" dir
            if ($0 ~ /^      args:[[:space:]]*$/) print "        - PROMETHEUS_API_BASE_IMAGE_HASH=" hash
        }
    ' "$f"
    echo ""

    # Collect named-volume entries (indented lines under a top-level volumes: key).
    vol_entries=$(awk '
        /^volumes:/        { vol=1; next }
        /^[^ #]/ && vol   { vol=0 }
        vol                { print }
    ' "$f")

    if [ -n "$vol_entries" ]; then
        all_vol_entries="${all_vol_entries}${vol_entries}
"
    fi
done

# ── Merged named volumes (if any agent declared them) ───────────────────────
if [ -n "$all_vol_entries" ]; then
    echo "volumes:"
    printf '%s' "$all_vol_entries"
fi
